// ADR-010 §七 —— 迁移链的单步脚本契约。
//
// 权威来源:
//   ADR-010 §七 —— 「加载时 `SaveVersion` 逐版本升级(0 → 1 → … → N),每步一个显式迁移脚本;
//                   **`WorldSeed` 与已发生事件原样保留**(ADR-007 §二 硬约束)」
//   GDD `persistence-service.md:563-567` —— AC-7a-14 全文
//   GDD `:181-185` 规则十
//
// ─────────────────────────────────────────────────────────────────────────────
// 为什么单独立契约,而不是把迁移写成 `SaveService` 里的一排 if
// ─────────────────────────────────────────────────────────────────────────────
// ADR-010 §七 的字面是「**每步一个显式迁移脚本**」。一排 `if (v == 0) {...} else if (v == 1) {...}`
// 能跑,但它把三件事糊在一起:① 有哪些版本存在;② 每步做什么;③ 链怎么驱动。
// 分开之后 ③(驱动)可以**在没有任何真实历史版本的情况下**被夹具钉住 ——
// 这正是本条债今日的处境:全库 `CurrentSaveVersion = 1` 且零 `v0` 写入者
// ⇒ **不存在真实的历史版本可以迁**。框架先立,真实脚本随版本升级逐条落。
//
// ⚠️ **本条不实现任何真实迁移**。`AC-7a-14` 的判据面(逐版本执行 + 两不变量)
// 由框架夹具以**测试内定义的假迁移步**钉住;**「v0 → v1 的真实脚本」不在本条面内**,
// 因为那需要一个**真实存在过的 v0 布局**作为输入,而它从未存在过。
// 造一个假 v0 再迁它,测的是夹具自己,不是产品行为 —— 那是自造断言的变体。
// ⇒ 真实脚本的落点 = **`CurrentSaveVersion` 第一次升到 2 的那一轮**。
//
// 🔁 **2026-10-28 ADR-034 就地加注(上文原文不删)** —— 「第一次升到 2 的那一轮」**已经发生**
// (即本轮),但**没有、也不该有** v1→v2 真实脚本,原因与上面「假 v0」的论证同型、但更硬:
// v2 新增的**载荷段**内容是 blob 字节,而 v1 存档**从未写出**它们 —— 不是「迁得不好」,
// 是**信息不存在**,任何脚本都补不出来。⇒ ADR-034 §⑥ 用 `SaveHeader.PayloadSegmentMinVersion`
// 把 `< 2` 的档**在链之前**单列拒收(`SaveService.Load`),不让它下沉到本链。
// ⇒ 本文第 15 行「全库 `CurrentSaveVersion = 1`」亦随之陈旧(现为 2)。
// 下一次真实脚本的落点 = **`CurrentSaveVersion` 第一次升到 3 的那一轮**(届时 v2→v3 有真输入)。

using System;

namespace DaYiJingCheng.Sim.Codec
{
    /// <summary>
    /// 存档迁移链的**单步**脚本:`SaveVersion == FromVersion` 的存档 ⇒ `FromVersion + 1`。
    /// <para><b>输入 / 输出都是「已剥掉校验和槽」的完整存档字节</b>
    /// (`magic + saveVersion + worldSeed + configVersion + tick + snapshotOffset + 正文`)。
    /// 理由:校验和覆盖的是「它之后的全部字节」(ADR-010 §四)⇒ 正文一变校验和必变,
    /// 链在最后统一重算一次即可;每步都算一次既浪费又给「某步忘了重算」留了口子。</para>
    /// <para>⚠️ <b>两条硬不变量由 <see cref="SaveMigrationChain"/> 在每步前后断言</b>
    /// (不由实现方自觉遵守):`WorldSeed` 逐位不变、已发生事件的字节段逐位不变。
    /// 实现方**不必**自己检查 —— 但**不得**依赖「没检查就能改」:链会当场抛。</para>
    /// </summary>
    public interface ISaveMigration
    {
        /// <summary>本步能迁移的**源**版本。迁完的产物版本恒为 <c>FromVersion + 1</c>。</summary>
        uint FromVersion { get; }

        /// <summary>
        /// 执行本步迁移。
        /// </summary>
        /// <param name="dataWithoutChecksum">已剥掉校验和槽的完整存档字节(**不会被就地修改**)。</param>
        /// <returns>迁移后的完整存档字节(仍**不含**校验和槽)。</returns>
        /// <exception cref="InvalidOperationException">
        /// 输入不是本步能处理的形态(版本号不符 / 长度不足 / 布局不认识)。
        /// <para>⚠️ 迁移失败须**抛**,不得返回原字节「当作成功」—— 后者会让
        /// 「迁移了但没变」与「迁移成功」在类型上不可分,是一处静默失败通道。</para>
        /// </exception>
        byte[] Migrate(byte[] dataWithoutChecksum);
    }
}
