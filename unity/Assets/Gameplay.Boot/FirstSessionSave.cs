// 「第一份存档」的建立(2026-11-04 · 用户裁定「只做首份存档(A)」)。
//
// ─────────────────────────────────────────────────────────────────────────────
// 它在补哪个窗口
// ─────────────────────────────────────────────────────────────────────────────
// GDD `persistence-service.md` 规则六的三个触发点,对**全新档**一个都不覆盖:
//   · 事件触发 —— 要求先有叙事事件(脉案落笔 / 病例结案 / 出诊启动),新局头几分钟没有;
//   · 定时兜底 —— 要到 `CHECKPOINT_INTERVAL`(默认 6000 tick ≙ 5 分钟)才第一次触发;
//   · 退出保存 —— 要玩家关窗;
//   · 手动槽   —— 要玩家主动打开存档位屏按「留档」。
// ⇒ **开局前 5 分钟内崩溃 / 强杀,盘上零存档**,「继续诊治」也无从谈起。
//
// ─────────────────────────────────────────────────────────────────────────────
// 归类:这是**定时兜底的 t = 0 实例**,不是第四个存档触发点
// ─────────────────────────────────────────────────────────────────────────────
// 规则六同时写死「存档只发生在三处」,`AC-7a-08` 判「恰三处」。本类**不新增类别**:
// 它写的槽位(`SaveService.AutoSaveSlot` = 2)与兜底**完全相同**,用的是**同一个**
// `Checkpoint` 入口,只是把「间隔已满」的判定从「过了 6000 tick」换成「这是第一份」。
// 因此三处计数不变 —— 若将来有人把本类改成写玩家槽 / 另开入口,那就真是第四类了。
//
// ─────────────────────────────────────────────────────────────────────────────
// 两条硬守卫(都不是「防御性设计」,各自对应一个已实测的失败形态)
// ─────────────────────────────────────────────────────────────────────────────
// ① **盘上已有任何档 ⇒ 一律不写。** 否则:读档失败后世界回落新局态,启动序末再存一次
//    就把玩家唯一能回的那份档覆盖成空世界 —— `BootRoot.TryContinueFromSave` 的注释
//    已经把这条立成约束(「新局不写任何存档文件 ⇒ 不覆盖既有档」)。
//    本类把该约束从「路径不发生」升级成「**写之前再查一次磁盘**」,因为
//    `_continueSlot == null` 有两种成因:真的没有档,或**查询失败**(见 ②)。
// ② **查询失败 ⇒ 不写。** `_continueSlot == null` 也可能是 `TryGetMostRecentSave`
//    抛了(目录不可读 / 权限);此时「有没有档」是**未知**,写下去可能覆盖上去。
//    「不知道」≠「没有」—— 与 ADR-037 §④「未知 ≠ 无差异」同一条纪律。
//
// ─────────────────────────────────────────────────────────────────────────────
// 失败方向
// ─────────────────────────────────────────────────────────────────────────────
// 本类**不抛**:启动序不得因为「第一份存档没写成」而中止(玩家连门都进不去)。
// 失败经 `error` 交给装配层记日志。另注意 `Checkpoint` 是**异步**的 —— 返回 true
// 只表示「已受理」,落盘在 worker 上;这不是缺陷,是 ADR-010 §六的既定形状。

using System;
using DaYiJingCheng.Sim.Codec;

namespace DaYiJingCheng.Gameplay.Boot
{
    /// <summary>全新档开局时的第一份存档(定时兜底的 t = 0 实例)。</summary>
    public static class FirstSessionSave
    {
        /// <summary>
        /// 若盘上**一个存档都没有**,写一份初始档到自动槽(槽 2)。
        /// </summary>
        /// <param name="saves">7a 存档服务;`null`(未装配存档目录)⇒ 直接返回 false,不算失败。</param>
        /// <param name="error">非 `null` ⇒ 本可写却失败了(查询失败 / 组版抛 / 门拒);供装配层记日志。</param>
        /// <returns>
        /// `true` = **已受理一次初始存档**;`false` = 没有写(已有档 / 查询失败 / 未装配 / 抛了)。
        /// <para>⚠️ `true` 不表示已落盘(`Checkpoint` 异步)。</para>
        /// </returns>
        public static bool TryEstablish(SaveService saves, out Exception error)
        {
            error = null;
            if (saves == null) return false;                     // 7a 未装配:合法形态,不是失败

            // 守卫①:已有档 ⇒ 绝不覆盖(哪怕本次是新局 / 读档失败回落)。
            if (saves.TryGetMostRecentSave(out _)) return false;

            // 守卫②:查询失败 = 「有没有档」未知 ⇒ 不写(不知道 ≠ 没有)。
            if (saves.LastSaveQueryError != null)
            {
                error = saves.LastSaveQueryError;
                return false;
            }

            try
            {
                saves.Checkpoint(SaveService.AutoSaveSlot);
            }
            catch (Exception e)
            {
                error = e;                                       // 启动序不因此中止,由调用方记日志
                return false;
            }

            return true;
        }
    }
}
